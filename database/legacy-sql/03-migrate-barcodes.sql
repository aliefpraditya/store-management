UNION ALL SELECT 'barang dengan barcode = SKU', COUNT(*), 3190 FROM products WHERE barcode = sku
UNION ALL SELECT 'barang dengan barcode lama (beda dari SKU)', COUNT(*), 668 FROM products WHERE barcode <> sku
